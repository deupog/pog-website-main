import Wrapper from '../containers/wrapper';
import { fetchEvents } from '@/features/notion/fetchEvents';

export const metadata = {
  title: 'Pog Website',
  description: 'Generated by create next app and Made with Elif and Esma',
};

export default async function Page() {
    const eventsData = await fetchEvents();
    const unihubKey = process.env.UNIHUB_PK || process.env.NEXT_PUBLIC_UNIHUB_PK;

    return (
        <>
            <Wrapper events={eventsData} unihubKey={unihubKey} />
        </>
    );
}